def lookup_dtc(code: str) -> DTCEntry:
    """Lookup a single DTC code against verified reference database."""
    clean_code = code.strip().upper()
    if clean_code in SAE_DTC_DATABASE:
        info = SAE_DTC_DATABASE[clean_code]
        return DTCEntry(
            code=clean_code,
            system=info["system"],
            description=info["description"],
            severity=info["severity"],
            escalate_risk=info["escalate_risk"],
            source=info.get("source", "SAE J2012 Verified Standard"),
            simple_title=info.get("simple_title", f"Diagnostic Code {clean_code}"),
            what_it_means=info.get("what_it_means", ""),
            what_you_might_notice=list(info.get("what_you_might_notice", [])),
            what_you_should_do=info.get("what_you_should_do", ""),
            urgency=info.get("urgency", "schedule_check"),
            urgency_label=info.get("urgency_label", "Schedule a Check"),
            why_it_matters=info.get("why_it_matters", ""),
            technical_details=info.get("technical_details", info["description"]),
            possible_causes=list(info.get("possible_causes", [])),
            limitations=list(info.get("limitations", [])),
        )

    # General SAE category decoding if specific code not in curated dictionary
    first_char = clean_code[0] if clean_code else "P"
    system_map = {"P": "Powertrain", "C": "Chassis", "B": "Body", "U": "Network"}
    system = system_map.get(first_char, "Automotive Subsystem")
    is_critical_subsystem = first_char in ("C", "U")

    return DTCEntry(
        code=clean_code,
        system=system,
        description=f"Standard Diagnostic Trouble Code ({system} Subsystem)",
        severity="critical" if is_critical_subsystem else "moderate",
        escalate_risk=is_critical_subsystem,  # Default conservative escalation for Chassis/Brake/Network
        source="SAE J2012 General Classification",
        simple_title=f"Diagnostic Code ({clean_code})",
        what_it_means="We recognize this as a diagnostic code, but we do not yet have a verified plain-English explanation for it. Have a qualified technician review the code and vehicle-specific information.",
        what_you_might_notice=[
            "Symptoms vary depending on the affected subsystem; monitor your vehicle for warning lamps or unusual behavior (may or may not occur)."
        ],
        what_you_should_do="Have a qualified technician review the code and vehicle-specific repair information using professional diagnostic tools.",
        urgency="prompt_attention" if is_critical_subsystem else "schedule_check",
        urgency_label="Prompt Attention" if is_critical_subsystem else "Schedule a Check",
        why_it_matters=f"This code relates to the vehicle's {system.lower()} systems and requires standard diagnostic equipment to isolate the cause.",
        technical_details=f"SAE J2012 standard trouble code under the {system} subsystem prefix ({first_char}). Specific component definitions depend on vehicle manufacturer service literature.",
        possible_causes=["Subsystem sensor fault", "Circuit wiring or connection issue", "Mechanical component wear"],
        limitations=["We recognize this as a diagnostic code, but we do not yet have a verified plain-English explanation for it."],
    )


def extract_dtcs_from_text(text: str) -> List[DTCEntry]:
    """Scan raw text or column values for valid SAE DTC codes."""
    matches = set(DTC_PATTERN.findall(text))
    return [lookup_dtc(code) for code in sorted(list(matches))]

