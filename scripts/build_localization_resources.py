def generate_all_arb_files() -> None:
    """Generate all 23 ARB files in apps/ios/lib/l10n/."""
    L10N_DIR.mkdir(parents=True, exist_ok=True)

    all_lang_codes = [
        "en", "hi", "ta", "te", "kn", "ml", "bn", "mr", "gu", "pa", "or", "as",
        "ur", "sa", "ks", "kok", "mni", "ne", "sd", "doi", "mai", "brx", "sat"
    ]

    for code in all_lang_codes:
        arb_path = L10N_DIR / f"app_{code}.arb"
        content: Dict[str, Any] = {"@@locale": code}

        if code == "en":
            # Add English keys and metadata
            for k, v in BASE_EN.items():
                content[k] = v
                content[f"@{k}"] = {"description": f"Localization key for {k}"}
        else:
            lang_dict = build_language_dictionary(code)
            for k in BASE_EN.keys():
                content[k] = lang_dict.get(k, BASE_EN[k])

        with open(arb_path, "w", encoding="utf-8") as f:
            json.dump(content, f, ensure_ascii=False, indent=2)

        print(f"Generated {arb_path.name} with {len(BASE_EN)} translation keys.")


if __name__ == "__main__":
    generate_all_arb_files()
